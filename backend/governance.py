import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional


class PIISanitizer:
    """
    Scrubs Personally Identifiable Information (PII) at the system boundary
    before any text is sent to an external LLM provider.
    """
    # Malaysian NRIC pattern: YYMMDD-PB-###G (e.g. 901231-14-5678 or 901231145678)
    NRIC_PATTERN = r'\b\d{6}-?\d{2}-?\d{4}\b'
    EMAIL_PATTERN = r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b'
    # Malaysian Phone Pattern: +601x-xxx xxxx or 01x-xxx xxxx
    PHONE_PATTERN = r'\b(?:\+?60|0)1[0-46-9]-?\d{7,8}\b'

    @classmethod
    def sanitize(cls, text: str) -> tuple[str, list[str]]:
        redacted = []

        if re.search(cls.NRIC_PATTERN, text):
            text = re.sub(cls.NRIC_PATTERN, "[REDACTED_NRIC]", text)
            redacted.append("NRIC")

        if re.search(cls.EMAIL_PATTERN, text):
            text = re.sub(cls.EMAIL_PATTERN, "[REDACTED_EMAIL]", text)
            redacted.append("EMAIL")

        if re.search(cls.PHONE_PATTERN, text):
            text = re.sub(cls.PHONE_PATTERN, "[REDACTED_PHONE]", text)
            redacted.append("PHONE")

        return text, redacted


class ComplianceGuardrail:
    """Enforces statutory financial compliance under Malaysian CMSA 2007."""

    MANDATORY_DISCLAIMER = (
        "\n\n---\n"
        "**REGULATORY DISCLAIMER (CMSA 2007)**:\n"
        "This report is generated by an automated AI financial analysis system for informational "
        "and educational purposes only. It does not constitute investment advice, financial research, "
        "or a recommendation to buy or sell any security under the Capital Markets and Services Act 2007. "
        "Investors must conduct their own independent due diligence or consult a licensed financial advisor."
    )

    @classmethod
    def apply_output_guardrails(cls, report_text: str) -> str:
        if "REGULATORY DISCLAIMER (CMSA 2007)" not in report_text:
            return report_text + cls.MANDATORY_DISCLAIMER
        return report_text


class AuditLedger:
    """
    Append-only audit ledger.
    Every single prompt, raw metrics, model output, and decision is written
    with cryptographic SHA-256 hashes and UTC timestamps for compliance audits.
    """
    LEDGER_FILE = Path(__file__).resolve().parent / "audit_ledger.jsonl"

    @classmethod
    def record_transaction(
        cls,
        user_query: str,
        stock_ticker: str,
        raw_metrics: dict,
        output_report: str,
        governance_metadata: dict
    ) -> str:
        timestamp = datetime.now(timezone.utc).isoformat()
        
        record_content = f"{timestamp}:{user_query}:{stock_ticker}:{output_report}"
        transaction_hash = hashlib.sha256(record_content.encode("utf-8")).hexdigest()

        entry = {
            "transaction_id": transaction_hash[:16],
            "timestamp_utc": timestamp,
            "user_query": user_query,
            "stock_ticker": stock_ticker,
            "raw_metrics": raw_metrics,
            "governance": governance_metadata,
            "sha256_hash": transaction_hash,
            "report_preview": output_report[:150] + "..."
        }

        with open(cls.LEDGER_FILE, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry) + "\n")

        return transaction_hash[:16]
